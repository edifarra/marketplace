-- Tabela temporaria para diagnosticar o retorno bruto das buscas de preco.
create table if not exists price_search_debug_results (
  id bigint generated by default as identity primary key,
  run_id uuid not null,
  searched_at timestamptz not null default now(),
  query text not null,
  category_description text,
  page_url text not null,
  page_offset integer not null,
  result_position integer not null,
  item_id text,
  product_id text,
  title text,
  price numeric(14,2),
  permalink text,
  eligible_for_collection boolean not null default false,
  collection_rejection_reason text
);

alter table price_search_debug_results enable row level security;

create index if not exists idx_price_search_debug_run
  on price_search_debug_results(run_id, page_offset, result_position);

create index if not exists idx_price_search_debug_item
  on price_search_debug_results(item_id);

create index if not exists idx_price_search_debug_product
  on price_search_debug_results(product_id);
